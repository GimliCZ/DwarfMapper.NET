using System.Collections.Immutable;
using System.Globalization;
using DwarfMapper.Generator.Diagnostics;
using Microsoft.CodeAnalysis;

namespace DwarfMapper.Generator.Tests
{
    /// <summary>
    ///     <c>[MapProperty(AllowNull = true)]</c> - the per-member statement that a null reaching a non-nullable
    ///     destination is deliberate. Owner ruling 2026-09-27: no DWARF warning may need a project-wide <c>NoWarn</c>;
    ///     each risk is accepted where it is, in mapping terms. It drops <c>DWARF070</c> (or the registry's
    ///     <c>DWARFR15</c>) for that one member and changes nothing else: the emitted assignment is byte-identical
    ///     with and without it, so every "with" below is compared against the same attribute without the statement.
    ///     A statement with nothing to accept is <c>DWARF116</c>, because a dead one is a pre-signed acceptance of a
    ///     null nobody has reviewed yet.
    /// </summary>
    /// <remarks>
    ///     Reach, as built: a member, a constructor parameter, a projected member - through the method-level, the
    ///     pair-scoped and the co-located host's member-placement forms, and the <c>[MapTo]</c> registry's member form.
    ///     NOT reached, and pinned so nobody widens it by accident: a null INSIDE the member (a collection element, a
    ///     dictionary value) and a null going into a converter's parameter - different edges, with their own remedies.
    /// </remarks>
    public class AllowNullIntentTests
    {
        private const string NullableName = "public string? Name { get; set; }";
        private const string NameDto = "public string Name { get; set; } = \"\";";
        private const string Allow = "[MapProperty(\"Name\", \"Name\", AllowNull = true)]";
        private const string NoAllow = "[MapProperty(\"Name\", \"Name\")]";

        private static string ClassModel(
            string methodAttributes,
            string source = NullableName,
            string target = NameDto,
            string mapperOptions = "",
            string method = "public partial B Map(A a);",
            string mapperBody = "")
        {
            return "using System.Collections.Generic;\nusing System.Linq;\nusing DwarfMapper;\nnamespace Demo;\n" +
                   "public class A { " + source + " }\n" +
                   "public class B { " + target + " }\n" +
                   "[DwarfMapper" + mapperOptions + "] public partial class M { " + mapperBody + " " + methodAttributes + " " + method + " }\n";
        }

        private static (ImmutableArray<Diagnostic> Diagnostics, string Generated) Run(string source)
        {
            return GeneratorTestHarness.Run(source, NullableContextOptions.Enable);
        }

        private static string Message(Diagnostic d)
        {
            return d.GetMessage(CultureInfo.InvariantCulture);
        }

        /// <summary>The same source with and without the statement: DWARF070 goes, and not one generated byte moves.</summary>
        private static void AssertAccepted(string withStatement, string withoutStatement, string reportId = "DWARF070")
        {
            var (withDiagnostics, withGenerated) = Run(withStatement);
            var (withoutDiagnostics, withoutGenerated) = Run(withoutStatement);

            Assert.Single(withoutDiagnostics, d => d.Id == reportId);
            Assert.DoesNotContain(withDiagnostics, d => d.Id is "DWARF070" or "DWARF116");
            Assert.False(string.IsNullOrWhiteSpace(withGenerated), "nothing was generated, so 'byte-identical' would prove nothing");
            Assert.Equal(withoutGenerated, withGenerated);
        }

        // ── The class model ─────────────────────────────────────────────────────────────────────────────

        [Fact]
        public void A_method_level_AllowNull_drops_DWARF070_and_changes_no_generated_byte()
        {
            AssertAccepted(ClassModel(Allow), ClassModel(NoAllow));
            Assert.Contains("Name = a.Name!", Run(ClassModel(Allow)).Generated, StringComparison.Ordinal);
        }

        [Fact]
        public void AllowNull_accepts_only_the_member_it_is_written_on()
        {
            var source = ClassModel(Allow,
                NullableName + " public string? Other { get; set; }",
                NameDto + " public string Other { get; set; } = \"\";");

            var d = Assert.Single(Run(source).Diagnostics, x => x.Id == "DWARF070");
            Assert.StartsWith("Source member 'Other' is a nullable reference", Message(d), StringComparison.Ordinal);
        }

        [Fact]
        public void DWARF070_names_the_member_AllowNull_would_be_written_for_and_offers_it()
        {
            var d = Assert.Single(Run(ClassModel(NoAllow)).Diagnostics, x => x.Id == "DWARF070");

            Assert.Equal("Name", d.Properties[DiagnosticInfo.MemberPropertyKey]);
            Assert.Contains("[MapProperty(source, destination, AllowNull = true)]", Message(d), StringComparison.Ordinal);
        }

        [Fact]
        public void AllowNull_reaches_a_constructor_parameter()
        {
            const string template = """
                                    using DwarfMapper;
                                    namespace Demo;
                                    public class A { public string? Name { get; set; } }
                                    public record B(string Name);
                                    [DwarfMapper] public partial class M { ATTR public partial B Map(A a); }
                                    """;

            AssertAccepted(template.Replace("ATTR", Allow, StringComparison.Ordinal),
                template.Replace("ATTR", NoAllow, StringComparison.Ordinal));
        }

        [Fact]
        public void A_stale_AllowNull_on_a_constructor_parameter_is_reported_once_not_again_by_the_member_path()
        {
            const string source = """
                                   using DwarfMapper;
                                   namespace Demo;
                                   public class A { public string Name { get; set; } = ""; }
                                   public record B(string Name);
                                   [DwarfMapper] public partial class M { [MapProperty("Name", "Name", AllowNull = true)] public partial B Map(A a); }
                                   """;

            var d = Assert.Single(Run(source).Diagnostics, x => x.Id == "DWARF116");
            Assert.Contains("its source is not a nullable reference", Message(d), StringComparison.Ordinal);
        }

        [Fact]
        public void A_pair_scoped_AllowNull_reaches_a_GenerateMap_pair()
        {
            const string template = """
                                    using DwarfMapper;
                                    namespace Demo;
                                    public class A { public string? Name { get; set; } }
                                    public class B { public string Name { get; set; } = ""; }
                                    [DwarfMapper]
                                    [GenerateMap<A, B>]
                                    ATTR
                                    public partial class M { }
                                    """;

            AssertAccepted(template.Replace("ATTR", "[MapProperty<A, B>(\"Name\", \"Name\", AllowNull = true)]", StringComparison.Ordinal),
                template.Replace("ATTR", "[MapProperty<A, B>(\"Name\", \"Name\")]", StringComparison.Ordinal));
        }

        [Fact]
        public void A_pair_scoped_AllowNull_reaches_a_nested_element_pair()
        {
            const string template = """
                                    using System.Collections.Generic;
                                    using DwarfMapper;
                                    namespace Demo;
                                    public class A { public string? Name { get; set; } }
                                    public class B { public string Name { get; set; } = ""; }
                                    public class AList { public List<A> Items { get; set; } = new(); }
                                    public class BList { public List<B> Items { get; set; } = new(); }
                                    ATTR
                                    [DwarfMapper] public partial class M { public partial BList Map(AList a); }
                                    """;

            AssertAccepted(template.Replace("ATTR", "[MapProperty<A, B>(\"Name\", \"Name\", AllowNull = true)]", StringComparison.Ordinal),
                template.Replace("ATTR", "[MapProperty<A, B>(\"Name\", \"Name\")]", StringComparison.Ordinal));
        }

        [Fact]
        public void A_co_located_host_member_AllowNull_is_read_off_the_destination_member()
        {
            const string template = """
                                    using DwarfMapper;
                                    namespace Demo;
                                    public class A { public string? Name { get; set; } }
                                    [GenerateMap<A, B>]
                                    public sealed class B { ATTR public string Name { get; set; } = ""; }
                                    """;

            AssertAccepted(template.Replace("ATTR", "[MapProperty(\"Name\", AllowNull = true)]", StringComparison.Ordinal),
                template.Replace("ATTR", "[MapProperty(\"Name\")]", StringComparison.Ordinal));
        }

        [Fact]
        public void AllowNull_reaches_an_update_into_map()
        {
            AssertAccepted(ClassModel(Allow, method: "public partial void Map(A a, B b);"),
                ClassModel(NoAllow, method: "public partial void Map(A a, B b);"));
        }

        // ── The projection endpoint ─────────────────────────────────────────────────────────────────────

        [Fact]
        public void AllowNull_reaches_a_projected_member_and_is_translatable()
        {
            const string method = "public partial IQueryable<B> Project(IQueryable<A> q);";
            AssertAccepted(ClassModel(Allow, method: method), ClassModel(NoAllow, method: method));
            // It rides the explicit map, not the extras NullSubstitute/When ride, so the untranslatable-modifier
            // refusal cannot see it - and must not: it changes nothing a provider has to translate.
            Assert.DoesNotContain(Run(ClassModel(Allow, method: method)).Diagnostics, d => d.Id == "DWARF028");
        }

        [Theory]
        [InlineData("[MapProperty(\"A\", \"Copy\", AllowNull = true)]")]
        [InlineData("[MapProperty(\"A\", \"A\", AllowNull = true)] [MapProperty(\"A\", \"Copy\")]")]
        public void A_projection_AllowNull_on_one_binding_leaves_the_other_binding_of_the_same_source_reported(string attributes)
        {
            // Projection reports DWARF070 once per SOURCE member, and the dedup used to run as each report was made:
            // whichever binding came first stood for both. Accepting that one then silenced the other. Settled now
            // after the method resolves - acceptance first, then one per source - in both orders.
            var source = ClassModel(attributes,
                "public string? A { get; set; }",
                "public string A { get; set; } = \"\"; public string Copy { get; set; } = \"\";",
                method: "public partial IQueryable<B> Project(IQueryable<A> q);");

            var (diagnostics, generated) = Run(source);

            var d = Assert.Single(diagnostics, x => x.Id == "DWARF070");
            Assert.StartsWith("Source member 'A' is a nullable reference", Message(d), StringComparison.Ordinal);
            Assert.DoesNotContain(diagnostics, x => x.Id == "DWARF116");
            Assert.Contains(GeneratorAssert.NormalizeLocals("Copy = __s.A!,"), GeneratorAssert.NormalizeLocals(generated), StringComparison.Ordinal);
            Assert.Contains(GeneratorAssert.NormalizeLocals("A = __s.A!,"), GeneratorAssert.NormalizeLocals(generated), StringComparison.Ordinal);
        }

        [Fact]
        public void A_stale_projection_AllowNull_is_reported()
        {
            var source = ClassModel(Allow, "public string Name { get; set; } = \"\";", method: "public partial IQueryable<B> Project(IQueryable<A> q);");

            var d = Assert.Single(Run(source).Diagnostics, x => x.Id == "DWARF116");
            Assert.StartsWith("[MapProperty(AllowNull = true)] on 'Name' accepts a null that cannot reach it", Message(d), StringComparison.Ordinal);
        }

        // ── What it does not reach ──────────────────────────────────────────────────────────────────────

        [Fact]
        public void AllowNull_on_a_collection_member_does_not_reach_a_null_element()
        {
            // The element edge that reports (round 29 T2.9): a nullable element into a declared converter whose
            // parameter is non-nullable. The statement is about the member's own value, which is a list.
            const string source = """
                                  using System.Collections.Generic;
                                  using DwarfMapper;
                                  namespace Demo;
                                  public class Child { public int V { get; set; } }
                                  public class ChildDto { public int V { get; set; } }
                                  public class A { public List<Child?> Items { get; set; } = new(); }
                                  public class B { public List<ChildDto> Items { get; set; } = new(); }
                                  [DwarfMapper] public partial class M
                                  {
                                      [MapProperty("Items", "Items", AllowNull = true)] public partial B Map(A a);
                                      public partial ChildDto ToDto(Child c);
                                  }
                                  """;

            var diagnostics = Run(source).Diagnostics;

            var element = Assert.Single(diagnostics, x => x.Id == "DWARF070");
            Assert.StartsWith("The source element mapped into 'Items'", Message(element), StringComparison.Ordinal);
            var stale = Assert.Single(diagnostics, x => x.Id == "DWARF116");
            Assert.Contains("a null INSIDE it", Message(stale), StringComparison.Ordinal);
            Assert.DoesNotContain("__DwarfMap", Message(stale), StringComparison.Ordinal);
        }

        [Fact]
        public void AllowNull_beside_a_converter_does_not_reach_the_converters_parameter()
        {
            var source = ClassModel("[MapProperty(\"Name\", \"Name\", Use = nameof(Upper), AllowNull = true)]",
                mapperBody: "private static string Upper(string s) => s.ToUpperInvariant();");

            var diagnostics = Run(source).Diagnostics;

            Assert.Single(diagnostics, x => x.Id == "DWARF070");
            var stale = Assert.Single(diagnostics, x => x.Id == "DWARF116");
            Assert.Contains("goes through 'Upper', whose parameter is what refuses the null", Message(stale), StringComparison.Ordinal);
        }

        // ── Stale statements ────────────────────────────────────────────────────────────────────────────

        [Theory]
        [InlineData("public string Name { get; set; } = \"\";", NameDto, "", "its source is not a nullable reference")]
        [InlineData(NullableName, "public string? Name { get; set; }", "", "its destination accepts null")]
        [InlineData(NullableName, NameDto, ", NullSubstitute = \"none\"", "its NullSubstitute already replaces the null")]
        public void A_stale_AllowNull_is_reported_as_DWARF116_with_its_reason(string source, string target, string extra, string reason)
        {
            var model = ClassModel("[MapProperty(\"Name\", \"Name\"" + extra + ", AllowNull = true)]", source, target);

            var d = Assert.Single(Run(model).Diagnostics, x => x.Id == "DWARF116");
            Assert.Equal(DiagnosticSeverity.Warning, d.Severity);
            Assert.Equal(
                "[MapProperty(AllowNull = true)] on 'Name' accepts a null that cannot reach it: " + reason + ". Remove " +
                "AllowNull - left in place, it would silently accept a null introduced here later, one nobody has reviewed.",
                Message(d));
        }

        [Fact]
        public void AllowNull_under_SkipNullSourceMembers_is_stale_because_the_class_option_already_keeps_the_destination_default()
        {
            // Correct, not a false positive: SkipNullSourceMembers guards the assignment, so no null reaches the
            // destination and the statement accepts nothing. Do not "fix" this by exempting the option.
            var model = ClassModel(Allow, mapperOptions: "(SkipNullSourceMembers = true)");

            var d = Assert.Single(Run(model).Diagnostics, x => x.Id == "DWARF116");
            Assert.Contains("SkipNullSourceMembers = true)] already keeps the destination's value", Message(d), StringComparison.Ordinal);
        }

        // ── The [MapTo] registry's member form ──────────────────────────────────────────────────────────

        [Fact]
        public void A_registry_member_AllowNull_drops_DWARFR15_and_changes_no_generated_byte()
        {
            const string template = """
                                    using DwarfMapper;
                                    namespace Demo;
                                    [MapTo(typeof(Dto))] public class Src { ATTR public string? Name { get; set; } }
                                    public class Dto { public string Name { get; set; } = ""; }
                                    """;

            var (withDiagnostics, withGenerated) = GeneratorTestHarness.RunMapToWithSource(
                template.Replace("ATTR", "[MapProperty(\"Name\", AllowNull = true)]", StringComparison.Ordinal),
                NullableContextOptions.Enable);
            var (withoutDiagnostics, withoutGenerated) = GeneratorTestHarness.RunMapToWithSource(
                template.Replace("ATTR", "[MapProperty(\"Name\")]", StringComparison.Ordinal),
                NullableContextOptions.Enable);

            var r15 = Assert.Single(withoutDiagnostics, d => d.Id == "DWARFR15");
            Assert.Contains("[MapProperty(\"Name\", AllowNull = true)] on the source member accepts it", Message(r15), StringComparison.Ordinal);
            Assert.DoesNotContain(withDiagnostics, d => d.Id is "DWARFR15" or "DWARF116");
            Assert.Equal(withoutGenerated, withGenerated);
            Assert.Contains("Name = source.Name!,", withGenerated, StringComparison.Ordinal);
        }

        [Fact]
        public void A_registry_AllowNull_on_a_member_no_null_reaches_is_DWARF116()
        {
            const string source = """
                                  using DwarfMapper;
                                  namespace Demo;
                                  [MapTo(typeof(Dto))] public class Src { [MapProperty("Name", AllowNull = true)] public string Name { get; set; } = ""; }
                                  public class Dto { public string Name { get; set; } = ""; }
                                  """;

            var d = Assert.Single(GeneratorTestHarness.RunMapTo(source, NullableContextOptions.Enable), x => x.Id == "DWARF116");
            Assert.Contains("its source is not a nullable reference", Message(d), StringComparison.Ordinal);
        }

        [Fact]
        public void A_registry_member_AllowNull_does_not_reach_a_null_element()
        {
            const string source = """
                                  using System.Collections.Generic;
                                  using DwarfMapper;
                                  namespace Demo;
                                  [MapTo(typeof(Dto))] public class Src { [MapProperty("Tags", AllowNull = true)] public List<string?> Tags { get; set; } = new(); }
                                  public class Dto { public List<string> Tags { get; set; } = new(); }
                                  """;

            var diagnostics = GeneratorTestHarness.RunMapTo(source, NullableContextOptions.Enable);

            var r15 = Assert.Single(diagnostics, x => x.Id == "DWARFR15");
            Assert.StartsWith("The source element mapped into 'Tags'", Message(r15), StringComparison.Ordinal);
            var stale = Assert.Single(diagnostics, x => x.Id == "DWARF116");
            Assert.Contains("the DWARFR15 beside this names it", Message(stale), StringComparison.Ordinal);
        }
    }
}
