// Regression tests for MapEmitter's EmitMappingPlanDoc summary on a VOID update-into method. The mapping-plan doc
// (Phase B, 37b684b) gave a method that returns nothing its own summary: "maps from S onto an existing target". It
// tested `ReturnTypeFullName == "void"`, but the update-into model that arrived later records the DESTINATION type there
// and carries the void return in UpdateReturnsVoid. So that summary was never emitted, and `void Update(Src, Dst)` was
// documented as "maps Src to Dst", the wording of a method that builds a Dst. It builds nothing: it writes into the one
// the caller passed.
namespace DwarfMapper.Generator.Tests.Coverage
{
    public class VoidUpdateIntoPlanSummaryTests
    {
        [Fact]
        public void A_void_update_into_method_is_documented_as_mapping_onto_an_existing_target()
        {
            const string source = """
                                  using DwarfMapper;
                                  namespace Demo;
                                  public class Src { public int A { get; set; } }
                                  public class Dst { public int A { get; set; } }
                                  [DwarfMapper]
                                  public partial class M { public partial void Update(Src s, Dst d); }
                                  """;

            var generated = GeneratorAssert.EmitsCompilableCode(source);

            Assert.Contains("/// <summary>Generated by DwarfMapper — maps from <c>global::Demo.Src</c> onto an existing target.</summary>", generated, StringComparison.Ordinal);
        }

        [Fact]
        public void A_returning_update_into_method_keeps_its_source_to_destination_summary()
        {
            const string source = """
                                  using DwarfMapper;
                                  namespace Demo;
                                  public class Src { public int A { get; set; } }
                                  public class Dst { public int A { get; set; } }
                                  [DwarfMapper]
                                  public partial class M { public partial Dst Update(Src s, Dst d); }
                                  """;

            var generated = GeneratorAssert.EmitsCompilableCode(source);

            Assert.Contains("/// <summary>Generated by DwarfMapper — maps <c>global::Demo.Src</c> to <c>global::Demo.Dst</c>.</summary>", generated, StringComparison.Ordinal);
        }
    }
}
