"""Rank Generator.Tests' test classes and methods by the mutants they killed (round 34 E4).

Usage:  python3 scripts/kill-ranking.py REPORT.json [REPORT.json ...]

Reads Stryker mutation-report.json files (the legs that run Generator.Tests: generator, pipeline, codefixes,
doctooling; CI uploads each as the artifact mutation-report-<leg>) and rewrites
tests/DwarfMapper.Generator.Tests/MutationKillRanking.tsv, which KillersFirstOrderer reads: Stryker stops a mutant's
session at its first failing test, so running the tests that killed the most first ends a killed mutant's session
early. The order changes no verdict, so a stale ranking costs time, never a result. Refresh it after a mutation round
whose reports carry renamed or new test classes.
"""

import collections
import io
import json
import os
import re
import sys

OUT = os.path.join('tests', 'DwarfMapper.Generator.Tests', 'MutationKillRanking.tsv')
PREFIX = 'DwarfMapper.Generator.Tests.'


def main(paths):
    if not paths:
        sys.exit(__doc__)
    by_class = collections.Counter()
    by_method = collections.Counter()
    for path in paths:
        report = json.load(io.open(path, encoding='utf-8'))
        names = {t['id']: t['name'] for tf in report.get('testFiles', {}).values() for t in tf.get('tests', [])}
        for f in report['files'].values():
            for m in f['mutants']:
                if m['status'] != 'Killed':
                    continue
                for tid in m.get('killedBy') or []:
                    name = names.get(tid)
                    if not name or not name.startswith(PREFIX):
                        continue
                    method = re.sub(r'\(.*$', '', name)  # a theory row counts toward its method
                    by_class[method.rpartition('.')[0]] += 1
                    by_method[method] += 1
    with io.open(OUT, 'w', encoding='utf-8', newline='\n') as w:
        w.write('# Kills per test class and method in the mutation reports below; KillersFirstOrderer runs the most-killing\n')
        w.write('# first. Generated by scripts/kill-ranking.py - do not edit by hand. Reports:\n')
        for path in paths:
            w.write('#   ' + '/'.join(os.path.abspath(path).replace(os.sep, '/').split('/')[-4:]) + '\n')
        for name, n in sorted(by_class.items(), key=lambda kv: (-kv[1], kv[0])):
            w.write(f'class\t{n}\t{name}\n')
        for name, n in sorted(by_method.items(), key=lambda kv: (-kv[1], kv[0])):
            w.write(f'method\t{n}\t{name}\n')
    print(f'{OUT}: {len(by_class)} classes, {len(by_method)} methods, {sum(by_class.values())} kills')


if __name__ == '__main__':
    main(sys.argv[1:])
